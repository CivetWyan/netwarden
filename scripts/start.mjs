import path from 'node:path';
import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { ROOT } from '../src/store.mjs';
process.env.ELECTRON_CACHE = path.join(ROOT, '.cache', 'electron');
process.env.electron_config_cache = process.env.ELECTRON_CACHE;
process.env.ELECTRON_BUILDER_CACHE = path.join(ROOT, '.cache', 'electron-builder');
const require = createRequire(import.meta.url);
const executable = require('electron');
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(executable, [ROOT, ...process.argv.slice(2)], { stdio: 'inherit', env });
child.on('exit', (code, signal) => { if (signal) process.kill(process.pid, signal); else process.exit(code || 0); });
child.on('error', e => { console.error(e.message); process.exitCode = 1; });
